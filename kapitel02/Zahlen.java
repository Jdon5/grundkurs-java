package kapitel02;

/**
 * Zahlen
 */
public class Zahlen {
    public static void main(String[] args) {
        int hexadezimalZahl = 0xAA00; // Hexadezimal-Literal (Präfix 0x)
        int binaerZahl = 0b10101010; // Binär-Literal (Präfix 0b)

        //Ausgabe
        System.out.println("Hexadezimalzahl: "+ hexadezimalZahl);
        System.out.println("Binaere Zahl: "+ binaerZahl);
    }
}